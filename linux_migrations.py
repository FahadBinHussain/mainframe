#!/usr/bin/env python3
"""Explicit offline conversion adapters; never activate settings or parse secrets.

Git is used only as a grammar parser with includes disabled and isolated config
scope. No configured command, helper, filter, hook, URL or include is executed.
"""
from __future__ import annotations

import os
import re
import subprocess
from collections import Counter

ADAPTER_VERSION = 1
MAX_CONFIG_BYTES = 256 * 1024
MIGRATION_MAP = {
    '.gitconfig': {
        'adapter': 'git-portable-settings-v1',
        'target': '.gitconfig',
        'preservation': 'original bytes retained separately',
        'activation': 'never; offline subset only',
    },
    'persist/mpv/portable_config/mpv.conf': {
        'adapter': 'mpv-portable-options-v1',
        'target': '.config/mpv/mpv.conf',
        'source_layout': 'scoop-mpv-portable-config-v1',
        'preservation': 'original bytes retained separately',
        'activation': 'never; offline subset only',
    },
    'persist/yt-dlp/yt-dlp.conf': {
        'adapter': 'yt-dlp-portable-options-v1',
        'target': '.config/yt-dlp/config',
        'source_layout': 'scoop-yt-dlp-config-v1',
        'preservation': 'original bytes retained separately',
        'activation': 'never; offline subset only',
    },
    'qbittorrent/config/qBittorrent.ini': {
        'adapter': 'qbittorrent-portable-preferences-v1',
        'target': '.config/qBittorrent/qBittorrent.conf',
        'source_layout': 'mainframe-qbittorrent-profile-config-v1',
        'preservation': 'original bytes retained separately',
        'activation': 'never; offline subset only',
    },
    'quick-persist/flameshot/flameshot.ini': {
        'adapter': 'flameshot-portable-preferences-v1',
        'target': '.config/flameshot/flameshot.ini',
        'source_layout': 'mainframe-quick-persist-flameshot-ini-v1',
        'preservation': 'original bytes retained separately',
        'activation': 'never; offline subset only',
    },
}
# Only literal enum values can reach generated configuration. Unknown keys and
# values are not echoed: even a Git subsection name can contain private data.
RULES = {
    'core.autocrlf': {'true': 'input', 'input': 'input', 'false': 'false'},
    'core.eol': {'crlf': 'lf', 'native': 'lf', 'lf': 'lf'},
    'core.safecrlf': {v: v for v in ('true', 'false', 'warn')},
    'diff.algorithm': {v: v for v in ('myers', 'minimal', 'patience', 'histogram')},
    'merge.conflictstyle': {v: v for v in ('merge', 'diff3', 'zdiff3')},
    'color.ui': {v: v for v in ('auto', 'always', 'never', 'true', 'false')},
}
MPV_BOOLEAN_OPTIONS = frozenset({
    'fullscreen', 'force-window', 'input-default-bindings', 'osc',
    'save-position-on-quit',
})
MPV_FLAG_ALIASES = {'fs': 'fullscreen'}
YT_DLP_OPTION_ALIASES = {
    '-i': '--ignore-errors', '--ignore-errors': '--ignore-errors',
    '--abort-on-error': '--abort-on-error',
    '--no-ignore-errors': '--abort-on-error',
    '--no-abort-on-error': '--no-abort-on-error',
}
QBITTORRENT_BOOLEAN_SETTINGS = {
    ('GUI', r'TransferList\UseTorrentStatesColors'):
        'GUI/TransferList/UseTorrentStatesColors',
    ('Preferences', r'General\AlternatingRowColors'):
        'Preferences/General/AlternatingRowColors',
    ('Preferences', r'General\ExitConfirm'):
        'Preferences/General/ExitConfirm',
    ('Preferences', r'General\NoSplashScreen'):
        'Preferences/General/NoSplashScreen',
    ('Preferences', r'General\StatusbarDisplayed'):
        'Preferences/General/StatusbarDisplayed',
    ('Preferences', r'General\ToolbarDisplayed'):
        'Preferences/General/ToolbarDisplayed',
}
QBITTORRENT_FOLDED_KEYS = {
    (section.casefold(), key.casefold()): (section, key)
    for section, key in QBITTORRENT_BOOLEAN_SETTINGS
}
FLAMESHOT_COLOR_OPTIONS = frozenset({'drawColor', 'uiColor', 'contrastUiColor'})
FLAMESHOT_BOOLEAN_OPTIONS = frozenset({'showHelp'})
FLAMESHOT_INTEGER_RANGES = {'contrastOpacity': (0, 255)}
FLAMESHOT_ALLOWED_OPTIONS = (FLAMESHOT_COLOR_OPTIONS | FLAMESHOT_BOOLEAN_OPTIONS
                             | frozenset(FLAMESHOT_INTEGER_RANGES))


def convert_git_config(payload, runner=subprocess.run):
    """Return generated bytes (or None) and a value-free audit record.

    Missing/invalid settings remain blocked; this never claims complete config
    migration. Git's NUL output handles quoted values and multiline grammar.
    Duplicate supported keys are all blocked rather than selecting a winner.
    """
    result = {'adapter': MIGRATION_MAP['.gitconfig']['adapter'],
              'version': ADAPTER_VERSION, 'status': 'blocked',
              'decisions': [], 'activation': 'not-performed'}
    if len(payload) > MAX_CONFIG_BYTES:
        return None, dict(result, reason='config-size-limit')
    if b'\x00' in payload:
        return None, dict(result, reason='invalid-config')
    # Do not inherit GIT_CONFIG_COUNT, global/system config, tracing or pager
    # settings. An explicit --file - reads only this supplied fixture/config.
    env = {'PATH': os.defpath, 'LANG': 'C', 'LC_ALL': 'C',
           'GIT_CONFIG_NOSYSTEM': '1', 'GIT_CONFIG_GLOBAL': '/dev/null'}
    try:
        parsed = runner(['git', 'config', '--no-includes', '--null', '--list', '--file', '-'],
                        input=payload, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                        check=False, shell=False, timeout=5, env=env)
    except (OSError, subprocess.SubprocessError):
        return None, dict(result, reason='git-parser-unavailable-or-failed')
    if parsed.returncode != 0 or len(parsed.stdout) > MAX_CONFIG_BYTES * 2:
        return None, dict(result, reason='invalid-config')
    records = []
    try:
        if parsed.stdout and not parsed.stdout.endswith(b'\x00'):
            raise ValueError('invalid parser framing')
        for record in parsed.stdout.split(b'\x00')[:-1]:
            key, separator, value = record.partition(b'\n')
            # Unknown records may contain arbitrary encoded private data. Only
            # ASCII allowlisted key names ever become audit fields.
            name = key.decode('ascii', errors='replace')
            records.append((name, value if separator else None))
    except ValueError:
        return None, dict(result, reason='invalid-config')
    counts = Counter(key for key, _ in records)
    accepted = {}
    unknown = sum(1 for key, _ in records if key not in RULES)
    if unknown:
        result['decisions'].append({'status': 'blocked', 'reason': 'unmapped-or-sensitive-setting', 'count': unknown})
    for key in sorted(counts.keys() & RULES.keys()):
        decision = {'key': key}
        if counts[key] != 1:
            decision.update(status='blocked', reason='duplicate-setting', count=counts[key])
        else:
            raw = next(value for name, value in records if name == key)
            value = raw.decode('ascii', errors='replace').lower() if raw is not None else ''
            if value not in RULES[key]:
                decision.update(status='blocked', reason='unsupported-value')
            else:
                accepted[key] = RULES[key][value]
                decision.update(status='converted' if accepted[key] != value else 'retained',
                                reason='native-line-endings' if accepted[key] != value else 'portable-enum')
        result['decisions'].append(decision)
    result['accepted_settings'] = len(accepted)
    result['blocked_settings'] = sum(d.get('count', 1) for d in result['decisions'] if d['status'] == 'blocked')
    if not accepted:
        return None, dict(result, reason='no-supported-settings')
    lines = ['# Portable subset generated offline; original config is preserved separately.']
    section = None
    for key, value in sorted(accepted.items()):
        group, option = key.split('.', 1)
        if group != section:
            lines.append(f'[{group}]')
            section = group
        lines.append(f'\t{option} = {value}')
    result['status'] = 'converted-subset'
    return ('\n'.join(lines) + '\n').encode('ascii'), result


def convert_yt_dlp_config(payload):
    """Convert one exact, documented yt-dlp error-policy switch offline.

    This intentionally is not a general yt-dlp config parser. Only a single
    exact flag token per file is accepted. Any other non-comment line, option
    argument, duplicate, or mixed error-policy blocks the whole output so an
    unreviewed option or ordering effect cannot be mistaken for a conversion.
    """
    result = {'adapter': MIGRATION_MAP['persist/yt-dlp/yt-dlp.conf']['adapter'],
              'version': ADAPTER_VERSION, 'status': 'blocked',
              'decisions': [], 'activation': 'not-performed',
              'accepted_settings': 0, 'blocked_settings': 0}
    if len(payload) > MAX_CONFIG_BYTES:
        return None, dict(result, reason='config-size-limit', blocked_settings=1)
    if b'\x00' in payload:
        return None, dict(result, reason='invalid-config', blocked_settings=1)
    try:
        text = payload.decode('utf-8')
    except UnicodeDecodeError:
        return None, dict(result, reason='invalid-config', blocked_settings=1)
    if ('\ufeff' in text
            or any(ord(char) < 32 and char not in '\r\n\t' for char in text)):
        return None, dict(result, reason='invalid-config', blocked_settings=1)

    options = []
    unsupported_count = 0
    unsupported_form_count = 0
    non_comment_lines = 0
    token_pattern = re.compile(r'^(?P<option>-i|--[A-Za-z][A-Za-z0-9-]*)(?P<suffix>.*)$')
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        non_comment_lines += 1
        match = token_pattern.fullmatch(stripped)
        if not match:
            unsupported_count += 1
            continue
        option = match.group('option')
        canonical = YT_DLP_OPTION_ALIASES.get(option)
        if canonical is None:
            unsupported_count += 1
        elif match.group('suffix'):
            unsupported_form_count += 1
        else:
            options.append(canonical)

    counts = Counter(options)
    duplicate_count = sum(count for count in counts.values() if count > 1)
    mixed_policy = len(counts) > 1
    if unsupported_count:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'unmapped-or-sensitive-setting',
                                    'count': unsupported_count})
    if unsupported_form_count:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'unsupported-option-form',
                                    'count': unsupported_form_count})
    if duplicate_count:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'duplicate-setting',
                                    'count': duplicate_count})
    if mixed_policy:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'mixed-error-policy',
                                    'count': len(options)})

    if unsupported_count or unsupported_form_count or duplicate_count or mixed_policy:
        result['blocked_settings'] = non_comment_lines
        return None, dict(result, reason='unsupported-or-conflicting-settings')
    if not options:
        return None, dict(result, reason='no-supported-settings')

    option = options[0]
    result['decisions'].append({'option': option, 'status': 'retained',
                                'reason': 'documented-platform-neutral-option'})
    result['accepted_settings'] = 1
    result['status'] = 'converted-subset'
    lines = ['# Portable yt-dlp subset generated offline; original config is preserved separately.',
             option]
    return ('\n'.join(lines) + '\n').encode('ascii'), result


def convert_qbittorrent_config(payload):
    """Convert only six shared qBittorrent boolean preferences offline.

    The source is a Windows QSettings INI under the app's custom profile. Paths,
    WebUI/network/authentication values, scripts, torrent state, OS-specific
    settings, and unknown keys remain in the preserved original only.
    """
    source_key = 'qbittorrent/config/qBittorrent.ini'
    result = {'adapter': MIGRATION_MAP[source_key]['adapter'],
              'version': ADAPTER_VERSION, 'status': 'blocked',
              'decisions': [], 'activation': 'not-performed',
              'accepted_settings': 0, 'blocked_settings': 0}
    if len(payload) > MAX_CONFIG_BYTES:
        return None, dict(result, reason='config-size-limit', blocked_settings=1)
    if b'\x00' in payload:
        return None, dict(result, reason='invalid-config', blocked_settings=1)
    try:
        text = payload.decode('utf-8')
    except UnicodeDecodeError:
        return None, dict(result, reason='invalid-config', blocked_settings=1)
    if ('\ufeff' in text
            or any(ord(char) < 32 and char not in '\r\n' for char in text)
            or any(ord(char) == 127 for char in text)):
        return None, dict(result, reason='invalid-config', blocked_settings=1)

    section_pattern = re.compile(r'^\[([^\[\]\r\n]{1,256})\]$')
    key_pattern = re.compile(r'^[^\[\]\r\n=]{1,256}$')
    section = None
    records = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith(('#', ';')):
            continue
        if stripped.startswith('['):
            match = section_pattern.fullmatch(stripped)
            if not match or not match.group(1).strip():
                return None, dict(result, reason='invalid-config',
                                  blocked_settings=1)
            section = match.group(1).strip()
            continue
        if '=' not in stripped:
            return None, dict(result, reason='invalid-config',
                              blocked_settings=1)
        key, value = (part.strip() for part in stripped.split('=', 1))
        if not key_pattern.fullmatch(key) or not key:
            return None, dict(result, reason='invalid-config',
                              blocked_settings=1)
        records.append((section, key, value))

    occurrences = {key: [] for key in QBITTORRENT_BOOLEAN_SETTINGS}
    unknown_count = 0
    for current_section, key, value in records:
        folded = ((current_section or '').casefold(), key.casefold())
        canonical = QBITTORRENT_FOLDED_KEYS.get(folded)
        if canonical is None:
            unknown_count += 1
            continue
        occurrences[canonical].append((current_section, key, value))
    if unknown_count:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'unmapped-or-sensitive-setting',
                                    'count': unknown_count})

    accepted = {}
    blocked_count = unknown_count
    for (expected_section, expected_key), display_key in sorted(
            QBITTORRENT_BOOLEAN_SETTINGS.items()):
        values = occurrences[(expected_section, expected_key)]
        if not values:
            continue
        decision = {'key': display_key}
        if len(values) != 1:
            decision.update(status='blocked', reason='duplicate-setting',
                            count=len(values))
            blocked_count += len(values)
        else:
            actual_section, actual_key, value = values[0]
            if (actual_section, actual_key) != (expected_section, expected_key):
                decision.update(status='blocked', reason='noncanonical-key-name',
                                count=1)
                blocked_count += 1
            elif value not in ('true', 'false'):
                decision.update(status='blocked', reason='unsupported-value',
                                count=1)
                blocked_count += 1
            else:
                accepted[(expected_section, expected_key)] = value
                decision.update(status='retained',
                                reason='documented-shared-boolean-preference')
        result['decisions'].append(decision)

    result['accepted_settings'] = len(accepted)
    result['blocked_settings'] = blocked_count
    if not accepted:
        return None, dict(result, reason='no-supported-settings')

    lines = ['; Bounded qBittorrent preferences generated offline; original profile is preserved separately.']
    current_section = None
    for section_key in sorted(accepted):
        current, key = section_key
        if current != current_section:
            if current_section is not None:
                lines.append('')
            lines.append(f'[{current}]')
            current_section = current
        lines.append(f'{key}={accepted[section_key]}')
    result['status'] = 'converted-subset'
    return ('\n'.join(lines) + '\n').encode('ascii'), result


def convert_flameshot_config(payload):
    """Convert only the documented shared Flameshot UI subset offline.

    This is not a general QSettings/INI migrator. Paths, shortcuts, startup,
    notifications, upload data, other settings/sections, and unknown values
    remain only in the preserved source and are represented by blocker counts.
    """
    source_key = 'quick-persist/flameshot/flameshot.ini'
    result = {'adapter': MIGRATION_MAP[source_key]['adapter'],
              'version': ADAPTER_VERSION, 'status': 'blocked',
              'decisions': [], 'activation': 'not-performed',
              'accepted_settings': 0, 'blocked_settings': 0}
    if len(payload) > MAX_CONFIG_BYTES:
        return None, dict(result, reason='config-size-limit', blocked_settings=1)
    if b'\x00' in payload:
        return None, dict(result, reason='invalid-config', blocked_settings=1)
    try:
        text = payload.decode('utf-8')
    except UnicodeDecodeError:
        return None, dict(result, reason='invalid-config', blocked_settings=1)
    if ('\ufeff' in text
            or any(ord(char) < 32 and char not in '\r\n\t' for char in text)):
        return None, dict(result, reason='invalid-config', blocked_settings=1)

    records = []
    section = None
    key_pattern = re.compile(r'^[A-Za-z][A-Za-z0-9_-]*$')
    section_pattern = re.compile(r'^\[([A-Za-z][A-Za-z0-9_-]*)\]$')
    color_pattern = re.compile(r'^#[0-9A-Fa-f]{6}$')
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith(('#', ';')):
            continue
        if stripped.startswith('['):
            match = section_pattern.fullmatch(stripped)
            if not match:
                return None, dict(result, reason='invalid-config', blocked_settings=1)
            section = match.group(1)
            continue
        if '=' not in stripped:
            return None, dict(result, reason='invalid-config', blocked_settings=1)
        key, value = (part.strip() for part in stripped.split('=', 1))
        if not key_pattern.fullmatch(key):
            return None, dict(result, reason='invalid-config', blocked_settings=1)
        records.append((section, key, value))

    unknown_count = 0
    occurrences = {}
    for current_section, key, value in records:
        if current_section != 'General' or key not in FLAMESHOT_ALLOWED_OPTIONS:
            unknown_count += 1
            continue
        occurrences.setdefault(key, []).append(value)
    if unknown_count:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'unmapped-or-sensitive-setting',
                                    'count': unknown_count})

    accepted = {}
    blocked_count = unknown_count
    for key in sorted(occurrences):
        values = occurrences[key]
        decision = {'key': key}
        if len(values) != 1:
            decision.update(status='blocked', reason='duplicate-setting',
                            count=len(values))
            blocked_count += len(values)
        else:
            value = values[0]
            if key in FLAMESHOT_COLOR_OPTIONS:
                valid = color_pattern.fullmatch(value) is not None
                canonical = value.lower() if valid else ''
            elif key in FLAMESHOT_BOOLEAN_OPTIONS:
                valid = value.lower() in ('true', 'false')
                canonical = value.lower() if valid else ''
            else:
                low, high = FLAMESHOT_INTEGER_RANGES[key]
                decimal_value = value.lstrip('0') or '0'
                valid = (value.isascii() and value.isdecimal()
                         and len(decimal_value) <= 3
                         and low <= int(decimal_value) <= high)
                canonical = str(int(decimal_value)) if valid else ''
            if valid:
                accepted[key] = canonical
                decision.update(status='retained',
                                reason='documented-shared-ui-preference')
            else:
                decision.update(status='blocked', reason='unsupported-value')
                blocked_count += 1
        result['decisions'].append(decision)

    result['accepted_settings'] = len(accepted)
    result['blocked_settings'] = blocked_count
    if not accepted:
        return None, dict(result, reason='no-supported-settings')
    lines = ['; Portable Flameshot subset generated offline; original config is preserved separately.',
             '[General]']
    lines.extend(f'{key}={accepted[key]}' for key in sorted(accepted))
    result['status'] = 'converted-subset'
    return ('\n'.join(lines) + '\n').encode('ascii'), result


def convert_mpv_config(payload):
    """Convert only simple, global mpv booleans; never execute or activate config.

    Profile-scoped settings, paths, scripts, includes, device/backend choices,
    unknown options, and non-boolean values are excluded without echoing values.
    """
    result = {'adapter': MIGRATION_MAP['persist/mpv/portable_config/mpv.conf']['adapter'],
              'version': ADAPTER_VERSION, 'status': 'blocked',
              'decisions': [], 'activation': 'not-performed'}
    if len(payload) > MAX_CONFIG_BYTES:
        return None, dict(result, reason='config-size-limit')
    if b'\x00' in payload:
        return None, dict(result, reason='invalid-config')
    try:
        text = payload.decode('utf-8')
    except UnicodeDecodeError:
        return None, dict(result, reason='invalid-config')
    if '\ufeff' in text:
        return None, dict(result, reason='invalid-config')

    key_pattern = re.compile(r'^[A-Za-z][A-Za-z0-9-]*$')
    profile_pattern = re.compile(r'^\[([^\[\]]+)\]$')
    in_profile = False
    accepted_values = {}
    counts = Counter()
    raw_values = {}
    unknown_count = 0
    profile_count = 0

    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        body = line.split('#', 1)[0].strip()
        if not body:
            continue
        if body.startswith('['):
            match = profile_pattern.fullmatch(body)
            if not match:
                return None, dict(result, reason='invalid-config')
            in_profile = match.group(1) != 'default'
            continue
        if '=' in body:
            name, value = body.split('=', 1)
            name, value = name.strip(), value.strip()
        else:
            name, value = body, 'yes'  # mpv treats a valueless option as enabled.
        if not key_pattern.fullmatch(name):
            return None, dict(result, reason='invalid-config')
        if in_profile:
            profile_count += 1
            continue
        canonical_name = name[3:] if name.startswith('no-') else name
        canonical_name = MPV_FLAG_ALIASES.get(canonical_name, canonical_name)
        if canonical_name not in MPV_BOOLEAN_OPTIONS:
            unknown_count += 1
            continue
        counts[canonical_name] += 1
        if counts[canonical_name] == 1:
            # Alternate spellings are counted against the canonical option but
            # never migrated alone; this also blocks aliases from overriding it.
            raw_values[canonical_name] = value if canonical_name == name else None

    if unknown_count:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'unmapped-or-sensitive-setting',
                                    'count': unknown_count})
    if profile_count:
        result['decisions'].append({'status': 'blocked',
                                    'reason': 'profile-scoped-setting',
                                    'count': profile_count})
    for name in sorted(counts):
        decision = {'key': name}
        if counts[name] != 1:
            decision.update(status='blocked', reason='duplicate-setting', count=counts[name])
        elif raw_values[name] not in ('yes', 'no'):
            decision.update(status='blocked', reason='unsupported-value')
        else:
            accepted_values[name] = raw_values[name]
            decision.update(status='retained', reason='portable-boolean')
        result['decisions'].append(decision)

    result['accepted_settings'] = len(accepted_values)
    result['blocked_settings'] = (unknown_count + profile_count
                                  + sum(d.get('count', 1) for d in result['decisions']
                                        if d['status'] == 'blocked'
                                        and 'key' in d))
    if not accepted_values:
        return None, dict(result, reason='no-supported-settings')
    lines = ['# Portable mpv subset generated offline; original config is preserved separately.']
    lines.extend(f'{name} = {accepted_values[name]}' for name in sorted(accepted_values))
    result['status'] = 'converted-subset'
    return ('\n'.join(lines) + '\n').encode('ascii'), result
